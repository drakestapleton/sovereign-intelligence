#!/bin/sh
# Regenerate isa/sm121-forms.txt from gen/bw_enc_sm121.om with the pinned seeded omc.
# Usage: OMC=/path/to/omc gen/run.sh     (run from the repository root)
set -eu
OMC=${OMC:?set OMC to the pinned omega-mv seed compiler}
PIN=3ad9f10f64309e7acf8a725082b28e23a2a4aeb07e98322fb4dc0fcd8fc93194
ENC=fe16b024c3242d12c7c8ef759d84c34a22c7d21cba676cd987f4f3a1ff56ba86
got=$(sha256sum "$OMC" | cut -d' ' -f1)
[ "$got" = "$PIN" ] || { echo "omc sha256 $got is not the pin $PIN" >&2; exit 1; }
enc=$(sha256sum gen/bw_enc_sm121.om | cut -d' ' -f1)
[ "$enc" = "$ENC" ] || { echo "encoder sha256 $enc is not CUDApp b774723f's $ENC" >&2; exit 1; }
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
cat gen/bw_enc_sm121.om gen/isa.om | "$OMC" > "$tmp/isa-gen"
chmod +x "$tmp/isa-gen"
{
  echo "# sm_121 (GB10) instruction forms, generated by gen/isa.om probing gen/bw_enc_sm121.om"
  echo "# encoder: CUDApp rad:z4RxD8vXigmWg61nM8miQ8DVPAXEP @ b774723f om/encoder/bw_enc_sm121.om sha256 $ENC"
  echo "# compiler: omega-mv seed omc sha256 $PIN"
  echo "# F id op sel fix0 fix1 fix2 msk0 msk1 msk2 ctl   |   D id field m0 m1 m2 start width   (see isa/README.md)"
  "$tmp/isa-gen"
} > "$tmp/forms.txt"
mv "$tmp/forms.txt" isa/sm121-forms.txt
echo "isa/sm121-forms.txt: $(grep -c '^F' isa/sm121-forms.txt) forms, sha256 $(sha256sum isa/sm121-forms.txt | cut -d' ' -f1)"
